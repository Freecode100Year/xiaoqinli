package codegen

import (
	"fmt"
	"strings"

	"xiaoqinli/ast"
)

// GenerateTCCLI produces Tencent Cloud CLI (tccli) wrapper scripts from the given typed AST.
func GenerateTCCLI(root ast.Node) ([]byte, error) {
	g := &tccliGen{buf: &strings.Builder{}}

	prog, ok := root.(*ast.Program)
	if !ok {
		return nil, fmt.Errorf("XQL_E401: top-level node must be Program")
	}

	g.writeln("#!/bin/bash")
	g.writeln("# Generated by Xiaoqinli Transpiler for Tencent Cloud CLI (tccli)")
	g.writeln("# Requirement: Official Tencent Cloud CLI (tccli) installed and configured")
	g.writeln("")
	g.writeln("set -e")
	g.writeln("")

	// Check if tccli command exists
	g.writeln("# Verify tccli command availability")
	g.writeln("if ! command -v tccli &> /dev/null; then")
	g.writeln("    echo 'Error: Official Tencent Cloud CLI (tccli) is not installed.' >&2")
	g.writeln("    exit 1")
	g.writeln("fi")
	g.writeln("")

	// Emit functions
	for _, d := range prog.Decls {
		if fd, ok := d.(*ast.FunctionDecl); ok && fd.Name != "main" {
			if err := g.emitFunctionDecl(fd); err != nil {
				return nil, err
			}
			g.writeln("")
		}
	}

	// Emit main function body
	for _, d := range prog.Decls {
		if fd, ok := d.(*ast.FunctionDecl); ok && fd.Name == "main" {
			g.writeln("# Main Execution Entry")
			for _, stmt := range fd.Body {
				if err := g.emitStmt(stmt); err != nil {
					return nil, err
				}
			}
		}
	}

	return []byte(g.buf.String()), nil
}

type tccliGen struct {
	buf    *strings.Builder
	indent int
}

func (g *tccliGen) writeln(s string) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("    ")
	}
	g.buf.WriteString(s)
	g.buf.WriteByte('\n')
}

func (g *tccliGen) emitFunctionDecl(fd *ast.FunctionDecl) error {
	g.writeln(fmt.Sprintf("%s() {", fd.Name))
	g.indent++

	// Assign parameters from positional arguments $1, $2, ...
	for i, p := range fd.Params {
		g.writeln(fmt.Sprintf("local %s=\"$%d\"", p.Name, i+1))
	}

	for _, stmt := range fd.Body {
		if err := g.emitStmt(stmt); err != nil {
			return err
		}
	}

	g.indent--
	g.writeln("}")
	return nil
}

func (g *tccliGen) emitStmt(s ast.Node) error {
	switch stmt := s.(type) {
	case *ast.VarDecl:
		val, err := g.emitExpr(stmt.Value)
		if err != nil {
			return err
		}
		g.writeln(fmt.Sprintf("local %s=%s", stmt.Name, val))
		return nil
	case *ast.AssignStmt:
		val, err := g.emitExpr(stmt.Value)
		if err != nil {
			return err
		}
		targetStr, err := g.emitExpr(stmt.Target)
		if err != nil {
			targetStr = "tmp"
		}
		g.writeln(fmt.Sprintf("%s=%s", strings.TrimPrefix(targetStr, "$"), val))
		return nil
	case *ast.ReturnStmt:
		val, err := g.emitExpr(stmt.Value)
		if err != nil {
			return err
		}
		g.writeln(fmt.Sprintf("echo %s", val))
		g.writeln("return 0")
		return nil
	case *ast.ExprStmt:
		val, err := g.emitExpr(stmt.Expr)
		if err != nil {
			return err
		}
		g.writeln(val)
		return nil
	case *ast.IfStmt:
		cond, err := g.emitExpr(stmt.Cond)
		if err != nil {
			return err
		}
		g.writeln(fmt.Sprintf("if [ %s ]; then", cond))
		g.indent++
		for _, s := range stmt.Then {
			if err := g.emitStmt(s); err != nil {
				return err
			}
		}
		g.indent--
		if len(stmt.Else) > 0 {
			g.writeln("else")
			g.indent++
			for _, s := range stmt.Else {
				if err := g.emitStmt(s); err != nil {
					return err
				}
			}
			g.indent--
		}
		g.writeln("fi")
		return nil
	default:
		return nil
	}
}

func (g *tccliGen) emitExpr(e ast.Node) (string, error) {
	if e == nil {
		return "''", nil
	}
	switch expr := e.(type) {
	case *ast.Literal:
		if expr.ValueType == "String" {
			return fmt.Sprintf("\"%v\"", expr.Value), nil
		}
		return fmt.Sprintf("%v", expr.Value), nil
	case *ast.Ident:
		return fmt.Sprintf("\"$%s\"", expr.Name), nil
	case *ast.CallExpr:
		args := make([]string, len(expr.Args))
		for i, a := range expr.Args {
			argStr, err := g.emitExpr(a)
			if err != nil {
				return "", err
			}
			args[i] = argStr
		}
		if expr.Callee == "println" {
			return fmt.Sprintf("echo %s", strings.Join(args, " ")), nil
		}
		if strings.HasPrefix(expr.Callee, "tccli_") {
			// Translate tccli_cvm_DescribeInstances -> tccli cvm DescribeInstances ...
			serviceCmd := strings.Replace(expr.Callee, "tccli_", "", 1)
			parts := strings.Split(serviceCmd, "_")
			return fmt.Sprintf("tccli %s %s", strings.Join(parts, " "), strings.Join(args, " ")), nil
		}
		return fmt.Sprintf("%s %s", expr.Callee, strings.Join(args, " ")), nil
	case *ast.BinaryExpr:
		left, err := g.emitExpr(expr.Left)
		if err != nil {
			return "", err
		}
		right, err := g.emitExpr(expr.Right)
		if err != nil {
			return "", err
		}
		return fmt.Sprintf("%s %s %s", left, expr.Op, right), nil
	default:
		return "''", nil
	}
}
