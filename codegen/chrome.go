package codegen

import (
	"bytes"
	"encoding/json"
	"fmt"
	"strings"

	"xiaoqinli/ast"
)

// GenerateChrome generates a Chrome Extension (Manifest V3) bundle from XQL AST.
// The output is a JSON file containing manifest.json, popup.html, and popup.js.
func GenerateChrome(root ast.Node) ([]byte, error) {
	g := &chromeGen{buf: &strings.Builder{}}

	prog, ok := root.(*ast.Program)
	if !ok {
		return nil, fmt.Errorf("XQL_E401: top-level node must be Program")
	}

	g.writeln("// XQL Chrome Extension — generated by xiaoqinli")
	g.writeln("")
	g.writeln("function _xql_print(v) {")
	g.indent++
	g.writeIndent()
	g.writeln("const el = document.getElementById('output');")
	g.writeIndent()
	g.writeln("if (el) el.textContent += String(v) + '\\n';")
	g.writeIndent()
	g.writeln("console.log(v);")
	g.indent--
	g.writeln("}")
	g.writeln("")

	for _, d := range prog.Decls {
		if ed, ok := d.(*ast.EnumDecl); ok {
			g.emitEnumDecl(ed)
			g.writeln("")
		}
	}

	for _, d := range prog.Decls {
		if sd, ok := d.(*ast.StructDecl); ok {
			g.emitStructDecl(sd)
			g.writeln("")
		}
	}

	hasMain := false
	for _, d := range prog.Decls {
		fd, ok := d.(*ast.FunctionDecl)
		if !ok || fd.Name == "main" {
			if ok && fd.Name == "main" {
				hasMain = true
			}
			continue
		}
		if err := g.emitFunctionDecl(fd); err != nil {
			return nil, err
		}
		g.writeln("")
	}

	if hasMain {
		mainFn := findMain(prog)
		g.muts = collectMutables(mainFn.Body)
		g.writeln("document.addEventListener('DOMContentLoaded', function() {")
		g.indent++
		for _, stmt := range mainFn.Body {
			if err := g.emitNode(stmt); err != nil {
				return nil, err
			}
		}
		g.indent--
		g.writeln("});")
	}

	popupJS := g.buf.String()

	popupHTML := `<!DOCTYPE html>
<html>
<head>
  <meta charset="utf-8">
  <style>
    body { font-family: 'Courier New', monospace; min-width: 320px; padding: 16px; margin: 0; background: #1e1e2e; color: #cdd6f4; }
    h3 { margin: 0 0 8px; font-size: 14px; color: #89b4fa; }
    #output { white-space: pre-wrap; font-size: 13px; line-height: 1.5; }
  </style>
</head>
<body>
  <h3>XQL Output</h3>
  <div id="output"></div>
  <script src="popup.js"></script>
</body>
</html>`

	manifest := map[string]interface{}{
		"manifest_version": 3,
		"name":             "XQL Extension",
		"version":          "1.0",
		"description":      "Generated by xiaoqinli XQL compiler",
		"action": map[string]interface{}{
			"default_popup": "popup.html",
		},
	}

	bundle := map[string]interface{}{
		"manifest.json": manifest,
		"popup.html":    popupHTML,
		"popup.js":      popupJS,
	}

	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	if err := enc.Encode(bundle); err != nil {
		return nil, fmt.Errorf("XQL_E401: JSON encode error: %v", err)
	}
	return buf.Bytes(), nil
}

func findMain(prog *ast.Program) *ast.FunctionDecl {
	for _, d := range prog.Decls {
		if fd, ok := d.(*ast.FunctionDecl); ok && fd.Name == "main" {
			return fd
		}
	}
	return nil
}

type chromeGen struct {
	buf    *strings.Builder
	indent int
	muts   map[string]bool
}

func (g *chromeGen) write(s string)   { g.buf.WriteString(s) }
func (g *chromeGen) writeln(s string) { g.buf.WriteString(s); g.buf.WriteByte('\n') }
func (g *chromeGen) writeIndent() {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("    ")
	}
}

func (g *chromeGen) emitEnumDecl(ed *ast.EnumDecl) {
	g.writeIndent()
	g.write("const " + ed.Name + " = Object.freeze({ ")
	for i, v := range ed.Variants {
		if i > 0 {
			g.write(", ")
		}
		g.write(fmt.Sprintf("%s: %d", v, i))
	}
	g.writeln(" });")
}

func (g *chromeGen) emitStructDecl(sd *ast.StructDecl) {
	g.writeIndent()
	g.writeln("class " + sd.Name + " {")
	g.indent++
	g.writeIndent()
	g.write("constructor(")
	for i, f := range sd.Fields {
		if i > 0 {
			g.write(", ")
		}
		g.write(f.Name)
	}
	g.writeln(") {")
	g.indent++
	for _, f := range sd.Fields {
		g.writeIndent()
		g.writeln("this." + f.Name + " = " + f.Name + ";")
	}
	g.indent--
	g.writeIndent()
	g.writeln("}")
	g.indent--
	g.writeIndent()
	g.writeln("}")
}

func (g *chromeGen) emitFunctionDecl(fd *ast.FunctionDecl) error {
	g.muts = collectMutables(fd.Body)
	g.writeIndent()
	g.write("function " + fd.Name + "(")
	for i, p := range fd.Params {
		if i > 0 {
			g.write(", ")
		}
		g.write(p.Name)
	}
	g.writeln(") {")
	g.indent++
	for _, stmt := range fd.Body {
		if err := g.emitNode(stmt); err != nil {
			return err
		}
	}
	g.indent--
	g.writeIndent()
	g.writeln("}")
	return nil
}

func (g *chromeGen) emitNode(n ast.Node) error {
	switch node := n.(type) {
	case *ast.FunctionDecl:
		return g.emitFunctionDecl(node)
	case *ast.ReturnStmt:
		return g.emitReturn(node)
	case *ast.VarDecl:
		return g.emitVarDecl(node)
	case *ast.AssignStmt:
		return g.emitAssign(node)
	case *ast.IfStmt:
		return g.emitIf(node)
	case *ast.WhileStmt:
		return g.emitWhile(node)
	case *ast.ForStmt:
		return g.emitFor(node)
	case *ast.BreakStmt:
		g.writeIndent()
		g.writeln("break;")
		return nil
	case *ast.ContinueStmt:
		g.writeIndent()
		g.writeln("continue;")
		return nil
	case *ast.ExprStmt:
		return g.emitExprStmt(node)
	case *ast.StructDecl:
		g.emitStructDecl(node)
		return nil
	case *ast.EnumDecl:
		g.emitEnumDecl(node)
		return nil
	case *ast.MatchExpr:
		return g.emitMatch(node)
	default:
		return fmt.Errorf("XQL_E401: unsupported node %s", n.Kind())
	}
}

func (g *chromeGen) emitReturn(rs *ast.ReturnStmt) error {
	g.writeIndent()
	if rs.Value == nil {
		g.writeln("return;")
		return nil
	}
	g.write("return ")
	if err := g.emitExpr(rs.Value); err != nil {
		return err
	}
	g.writeln(";")
	return nil
}

func (g *chromeGen) emitVarDecl(vd *ast.VarDecl) error {
	g.writeIndent()
	if g.muts[vd.Name] {
		g.write("let ")
	} else {
		g.write("const ")
	}
	g.write(vd.Name)
	if vd.Value != nil {
		g.write(" = ")
		if err := g.emitExpr(vd.Value); err != nil {
			return err
		}
	}
	g.writeln(";")
	return nil
}

func (g *chromeGen) emitAssign(as *ast.AssignStmt) error {
	g.writeIndent()
	if err := g.emitExpr(as.Target); err != nil {
		return err
	}
	g.write(" = ")
	if err := g.emitExpr(as.Value); err != nil {
		return err
	}
	g.writeln(";")
	return nil
}

func (g *chromeGen) emitIf(is *ast.IfStmt) error {
	g.writeIndent()
	g.write("if (")
	if err := g.emitExpr(is.Cond); err != nil {
		return err
	}
	g.writeln(") {")
	g.indent++
	for _, s := range is.Then {
		if err := g.emitNode(s); err != nil {
			return err
		}
	}
	g.indent--
	g.writeIndent()
	if len(is.Else) > 0 {
		g.writeln("} else {")
		g.indent++
		for _, s := range is.Else {
			if err := g.emitNode(s); err != nil {
				return err
			}
		}
		g.indent--
		g.writeIndent()
	}
	g.writeln("}")
	return nil
}

func (g *chromeGen) emitWhile(ws *ast.WhileStmt) error {
	g.writeIndent()
	g.write("while (")
	if err := g.emitExpr(ws.Cond); err != nil {
		return err
	}
	g.writeln(") {")
	g.indent++
	for _, s := range ws.Body {
		if err := g.emitNode(s); err != nil {
			return err
		}
	}
	g.indent--
	g.writeIndent()
	g.writeln("}")
	return nil
}

func (g *chromeGen) emitFor(fs *ast.ForStmt) error {
	g.writeIndent()
	if fs.Form == "range" {
		g.write("for (let " + fs.Var + " = ")
		if err := g.emitExpr(fs.Start); err != nil {
			return err
		}
		g.write("; " + fs.Var + " < ")
		if err := g.emitExpr(fs.End); err != nil {
			return err
		}
		g.write("; " + fs.Var + "++")
	} else {
		g.write("for (const " + fs.Var + " of ")
		if err := g.emitExpr(fs.Iterable); err != nil {
			return err
		}
	}
	g.writeln(") {")
	g.indent++
	for _, s := range fs.Body {
		if err := g.emitNode(s); err != nil {
			return err
		}
	}
	g.indent--
	g.writeIndent()
	g.writeln("}")
	return nil
}

func (g *chromeGen) emitExprStmt(es *ast.ExprStmt) error {
	g.writeIndent()
	if err := g.emitExpr(es.Expr); err != nil {
		return err
	}
	g.writeln(";")
	return nil
}

func (g *chromeGen) emitMatch(me *ast.MatchExpr) error {
	g.writeIndent()
	g.write("switch (")
	if err := g.emitExpr(me.Value); err != nil {
		return err
	}
	g.writeln(") {")
	for _, arm := range me.Arms {
		g.writeIndent()
		if ident, ok := arm.Pattern.(*ast.Ident); ok && ident.Name == "_" {
			g.writeln("default:")
		} else {
			g.write("case ")
			if err := g.emitExpr(arm.Pattern); err != nil {
				return err
			}
			g.writeln(":")
		}
		g.indent++
		for _, s := range arm.Body {
			if err := g.emitNode(s); err != nil {
				return err
			}
		}
		g.writeIndent()
		g.writeln("break;")
		g.indent--
	}
	g.writeIndent()
	g.writeln("}")
	return nil
}

// --- expressions ---

func (g *chromeGen) emitExpr(n ast.Node) error {
	switch node := n.(type) {
	case *ast.Literal:
		return g.emitLiteral(node)
	case *ast.Ident:
		g.write(node.Name)
		return nil
	case *ast.BinaryExpr:
		g.write("(")
		if err := g.emitExpr(node.Left); err != nil {
			return err
		}
		g.write(" " + node.Op + " ")
		if err := g.emitExpr(node.Right); err != nil {
			return err
		}
		g.write(")")
		return nil
	case *ast.UnaryExpr:
		g.write(node.Op)
		return g.emitExpr(node.Operand)
	case *ast.CallExpr:
		return g.emitCall(node)
	case *ast.MemberExpr:
		if err := g.emitExpr(node.Object); err != nil {
			return err
		}
		g.write("." + node.Field)
		return nil
	case *ast.StructLit:
		g.write("new " + node.TypeName + "(")
		for i, f := range node.Fields {
			if i > 0 {
				g.write(", ")
			}
			if err := g.emitExpr(f.Value); err != nil {
				return err
			}
		}
		g.write(")")
		return nil
	case *ast.ArrayLit:
		g.write("[")
		for i, elem := range node.Elements {
			if i > 0 {
				g.write(", ")
			}
			if err := g.emitExpr(elem); err != nil {
				return err
			}
		}
		g.write("]")
		return nil
	case *ast.IndexExpr:
		if err := g.emitExpr(node.Target); err != nil {
			return err
		}
		g.write("[")
		if err := g.emitExpr(node.Index); err != nil {
			return err
		}
		g.write("]")
		return nil
	case *ast.IfExpr:
		g.write("(")
		if err := g.emitExpr(node.Cond); err != nil {
			return err
		}
		g.write(" ? ")
		if err := g.emitExpr(node.Then); err != nil {
			return err
		}
		g.write(" : ")
		if err := g.emitExpr(node.Else); err != nil {
			return err
		}
		g.write(")")
		return nil
	case *ast.Lambda:
		g.write("function(")
		for i, p := range node.Params {
			if i > 0 {
				g.write(", ")
			}
			g.write(p.Name)
		}
		g.write(") {")
		if len(node.Body) == 0 {
			g.write("}")
			return nil
		}
		g.writeln("")
		g.indent++
		for _, stmt := range node.Body {
			if err := g.emitNode(stmt); err != nil {
				return err
			}
		}
		g.indent--
		g.writeIndent()
		g.write("}")
		return nil
	default:
		return fmt.Errorf("XQL_E401: unsupported expression %s", n.Kind())
	}
}

func (g *chromeGen) emitCall(ce *ast.CallExpr) error {
	switch ce.Callee {
	case "println":
		g.write("_xql_print(")
		if len(ce.Args) > 0 {
			if err := g.emitExpr(ce.Args[0]); err != nil {
				return err
			}
		} else {
			g.write("\"\"")
		}
		g.write(")")
		return nil
	case "printf":
		g.write("_xql_print(")
		if len(ce.Args) > 0 {
			if err := g.emitExpr(ce.Args[0]); err != nil {
				return err
			}
		} else {
			g.write("\"\"")
		}
		g.write(")")
		return nil
	case "sprintf":
		g.write("String(")
		if len(ce.Args) > 0 {
			if err := g.emitExpr(ce.Args[0]); err != nil {
				return err
			}
		} else {
			g.write("\"\"")
		}
		g.write(")")
		return nil
	default:
		g.write(ce.Callee + "(")
		for i, arg := range ce.Args {
			if i > 0 {
				g.write(", ")
			}
			if err := g.emitExpr(arg); err != nil {
				return err
			}
		}
		g.write(")")
		return nil
	}
}

func (g *chromeGen) emitLiteral(lit *ast.Literal) error {
	switch lit.ValueType {
	case "String":
		s, _ := lit.Value.(string)
		g.write(fmt.Sprintf("%q", s))
	case "Int":
		f, _ := lit.Value.(float64)
		g.write(fmt.Sprintf("%d", int64(f)))
	case "Float":
		f, _ := lit.Value.(float64)
		g.write(fmt.Sprintf("%g", f))
	case "Bool":
		b, _ := lit.Value.(bool)
		g.write(fmt.Sprintf("%t", b))
	default:
		g.write(fmt.Sprintf("%v", lit.Value))
	}
	return nil
}
