package codegen

import (
	"encoding/json"
	"fmt"

	"xiaoqinli/ast"
)

// GenerateShortcut generates an Apple iOS Shortcuts workflow JSON from XQL AST.
// The output is a JSON file (.shortcut) that can be imported into the Shortcuts app.
func GenerateShortcut(root ast.Node) ([]byte, error) {
	g := &scGen{
		types:   newTypeKinds(root),
		actions: make([]map[string]interface{}, 0),
		funcs:   make(map[string]*ast.FunctionDecl),
	}

	prog, ok := root.(*ast.Program)
	if !ok {
		return nil, fmt.Errorf("XQL_E401: top-level node must be Program")
	}

	for _, d := range prog.Decls {
		if fd, ok := d.(*ast.FunctionDecl); ok {
			g.funcs[fd.Name] = fd
		}
	}

	g.addComment("XQL Shortcut — generated by xiaoqinli")

	for _, d := range prog.Decls {
		switch node := d.(type) {
		case *ast.EnumDecl:
			g.emitEnumDecl(node)
		case *ast.StructDecl:
			g.addComment("struct " + node.Name)
		}
	}

	mainFn := g.funcs["main"]
	if mainFn != nil {
		for _, stmt := range mainFn.Body {
			if err := g.emitStmt(stmt); err != nil {
				return nil, err
			}
		}
	} else {
		for _, d := range prog.Decls {
			fd, ok := d.(*ast.FunctionDecl)
			if !ok {
				continue
			}
			g.addComment("function " + fd.Name)
			for _, stmt := range fd.Body {
				if err := g.emitStmt(stmt); err != nil {
					return nil, err
				}
			}
		}
	}

	workflow := map[string]interface{}{
		"WFWorkflowMinimumClientVersionString": "900",
		"WFWorkflowMinimumClientVersion":       900,
		"WFWorkflowIcon": map[string]interface{}{
			"WFWorkflowIconStartColor":  4282601983,
			"WFWorkflowIconGlyphNumber": 59771,
		},
		"WFWorkflowClientVersion":            "2302.0.4",
		"WFWorkflowOutputContentItemClasses": []string{},
		"WFWorkflowHasOutputFallback":        false,
		"WFWorkflowActions":                  g.actions,
		"WFWorkflowImportQuestions":          []interface{}{},
		"WFWorkflowTypes":                    []string{},
		"WFWorkflowInputContentItemClasses":  []string{},
	}

	return json.MarshalIndent(workflow, "", "  ")
}

type scGen struct {
	types     *typeKinds
	actions   []map[string]interface{}
	funcs     map[string]*ast.FunctionDecl
	groupSeq  int
	tmpSeq    int
	callDepth int
}

func (g *scGen) addAction(id string, params map[string]interface{}) {
	g.actions = append(g.actions, map[string]interface{}{
		"WFWorkflowActionIdentifier": id,
		"WFWorkflowActionParameters": params,
	})
}

func (g *scGen) addComment(text string) {
	g.addAction("is.workflow.actions.comment", map[string]interface{}{
		"WFCommentActionText": text,
	})
}

func (g *scGen) nextGroupID() string {
	g.groupSeq++
	return fmt.Sprintf("XQL-%04d", g.groupSeq)
}

func (g *scGen) nextTmp() string {
	g.tmpSeq++
	return fmt.Sprintf("_xql_%d", g.tmpSeq)
}

func scVarRef(name string) map[string]interface{} {
	return map[string]interface{}{
		"Value": map[string]interface{}{
			"Type":         "Variable",
			"VariableName": name,
		},
		"WFSerializationType": "WFTextTokenAttachment",
	}
}

func scTextToken(s string) map[string]interface{} {
	return map[string]interface{}{
		"WFSerializationType": "WFTextTokenString",
		"Value": map[string]interface{}{
			"string":             s,
			"attachmentsByRange": map[string]interface{}{},
		},
	}
}

// --- statements ---

func (g *scGen) emitStmt(n ast.Node) error {
	switch node := n.(type) {
	case *ast.VarDecl:
		return g.emitVarDecl(node)
	case *ast.AssignStmt:
		return g.emitAssign(node)
	case *ast.ExprStmt:
		return g.emitExprStmt(node)
	case *ast.ReturnStmt:
		if node.Value != nil {
			return g.emitExpr(node.Value)
		}
		return nil
	case *ast.IfStmt:
		return g.emitIf(node)
	case *ast.WhileStmt:
		return g.emitWhile(node)
	case *ast.ForStmt:
		return g.emitFor(node)

	// Shortcuts has Repeat and Repeat With Each and nothing that leaves either
	// early. These two used to become comments, which is the shape XQL_E402
	// exists to prevent: a comment is not a jump, so the loop ran every
	// iteration and the workflow reported success. Declining says the same
	// thing lua, bat, elixir, haskell and ocaml already say about `continue`.
	case *ast.BreakStmt:
		return fmt.Errorf("XQL_E402: Shortcuts has no way to leave a Repeat early, so break cannot be expressed")
	case *ast.ContinueStmt:
		return fmt.Errorf("XQL_E402: Shortcuts has no way to skip to the next Repeat iteration, so continue cannot be expressed")
	case *ast.MatchExpr:
		return g.emitMatch(node)
	case *ast.StructDecl:
		g.addComment("struct " + node.Name)
		return nil
	case *ast.EnumDecl:
		g.emitEnumDecl(node)
		return nil
	default:
		return nil
	}
}

func (g *scGen) emitEnumDecl(ed *ast.EnumDecl) {
	for i, v := range ed.Variants {
		g.addAction("is.workflow.actions.number", map[string]interface{}{
			"WFNumberActionNumber": i,
		})
		g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
			"WFVariableName": ed.Name + "_" + v,
		})
	}
}

func (g *scGen) emitVarDecl(vd *ast.VarDecl) error {
	if vd.Value != nil {
		if err := g.emitExpr(vd.Value); err != nil {
			return err
		}
	} else {
		if vd.Type.KindName == "String" {
			g.addAction("is.workflow.actions.text", map[string]interface{}{
				"WFTextActionText": "",
			})
		} else {
			g.addAction("is.workflow.actions.number", map[string]interface{}{
				"WFNumberActionNumber": 0,
			})
		}
	}
	g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
		"WFVariableName": vd.Name,
	})
	return nil
}

func (g *scGen) emitAssign(as *ast.AssignStmt) error {
	if err := g.emitExpr(as.Value); err != nil {
		return err
	}
	if ident, ok := as.Target.(*ast.Ident); ok {
		g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
			"WFVariableName": ident.Name,
		})
	} else if ie, ok := as.Target.(*ast.IndexExpr); ok {
		if tgt, ok := ie.Target.(*ast.Ident); ok {
			g.addComment(fmt.Sprintf("%s[...] = ... (index assignment)", tgt.Name))
		}
	} else {
		g.addComment("complex assignment target")
	}
	return nil
}

func (g *scGen) emitExprStmt(es *ast.ExprStmt) error {
	if ce, ok := es.Expr.(*ast.CallExpr); ok {
		return g.emitCallStmt(ce)
	}
	return g.emitExpr(es.Expr)
}

func (g *scGen) emitCallStmt(ce *ast.CallExpr) error {
	switch ce.Callee {
	case "println":
		if len(ce.Args) == 0 {
			g.addAction("is.workflow.actions.showresult", map[string]interface{}{
				"Text": scTextToken(""),
			})
			return nil
		}
		if err := g.emitExpr(ce.Args[0]); err != nil {
			return err
		}
		g.addAction("is.workflow.actions.showresult", map[string]interface{}{})
		return nil
	case "printf":
		if len(ce.Args) > 0 {
			if err := g.emitExpr(ce.Args[0]); err != nil {
				return err
			}
			g.addAction("is.workflow.actions.showresult", map[string]interface{}{})
		}
		return nil
	default:
		return g.emitInlineCall(ce)
	}
}

func (g *scGen) emitInlineCall(ce *ast.CallExpr) error {
	fd, ok := g.funcs[ce.Callee]
	if !ok {
		g.addComment("call " + ce.Callee + " (unknown)")
		return nil
	}
	if g.callDepth > 10 {
		g.addComment("call " + ce.Callee + " (recursion limit)")
		return nil
	}
	g.callDepth++
	defer func() { g.callDepth-- }()
	for i, arg := range ce.Args {
		if i < len(fd.Params) {
			if err := g.emitExpr(arg); err != nil {
				return err
			}
			g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
				"WFVariableName": fd.Params[i].Name,
			})
		}
	}
	for _, stmt := range fd.Body {
		if err := g.emitStmt(stmt); err != nil {
			return err
		}
	}
	return nil
}

func (g *scGen) emitIf(is *ast.IfStmt) error {
	groupID := g.nextGroupID()

	if be, ok := is.Cond.(*ast.BinaryExpr); ok {
		if err := g.emitExpr(be.Left); err != nil {
			return err
		}
		params := map[string]interface{}{
			"WFControlFlowMode":  0,
			"GroupingIdentifier": groupID,
		}
		switch be.Op {
		case "==":
			params["WFCondition"] = 0
		case "!=":
			params["WFCondition"] = 1
		case ">":
			params["WFCondition"] = 2
		case ">=":
			params["WFCondition"] = 3
		case "<":
			params["WFCondition"] = 4
		case "<=":
			params["WFCondition"] = 5
		default:
			params["WFCondition"] = 0
		}
		g.setConditionValue(params, be.Right)
		g.addAction("is.workflow.actions.conditional", params)
	} else {
		if err := g.emitExpr(is.Cond); err != nil {
			return err
		}
		g.addAction("is.workflow.actions.conditional", map[string]interface{}{
			"WFControlFlowMode":  0,
			"GroupingIdentifier": groupID,
			"WFCondition":        2,
			"WFNumberValue":      0,
		})
	}

	for _, s := range is.Then {
		if err := g.emitStmt(s); err != nil {
			return err
		}
	}

	if len(is.Else) > 0 {
		g.addAction("is.workflow.actions.conditional", map[string]interface{}{
			"WFControlFlowMode":  1,
			"GroupingIdentifier": groupID,
		})
		for _, s := range is.Else {
			if err := g.emitStmt(s); err != nil {
				return err
			}
		}
	}

	g.addAction("is.workflow.actions.conditional", map[string]interface{}{
		"WFControlFlowMode":  2,
		"GroupingIdentifier": groupID,
	})
	return nil
}

func (g *scGen) setConditionValue(params map[string]interface{}, n ast.Node) {
	switch node := n.(type) {
	case *ast.Literal:
		switch node.ValueType {
		case "Int":
			f, _ := node.Value.(float64)
			params["WFNumberValue"] = int64(f)
		case "Float":
			f, _ := node.Value.(float64)
			params["WFNumberValue"] = f
		case "String":
			s, _ := node.Value.(string)
			params["WFConditionalActionString"] = s
		case "Bool":
			b, _ := node.Value.(bool)
			if b {
				params["WFNumberValue"] = 1
			} else {
				params["WFNumberValue"] = 0
			}
		}
	case *ast.Ident:
		params["WFNumberValue"] = scVarRef(node.Name)
	default:
		params["WFNumberValue"] = 0
	}
}

// emitWhile declines. Shortcuts' only loops are Repeat, which takes a count,
// and Repeat With Each, which takes a list; neither reads a condition, and
// there is no action that ends a Repeat early. This backend used to emit
// `Repeat 1000` and throw the condition away, which is not a while loop —
// while_accumulate.xql.json would have run 1000 times instead of 3, and
// control_flow.xql.json, whose only exit is a `break`, would have run 1000
// times instead of 7. Both compiled, and the smoke tier could not see it.
func (g *scGen) emitWhile(ws *ast.WhileStmt) error {
	return fmt.Errorf("XQL_E402: Shortcuts' Repeat actions take a count or a list, not a condition, so a while loop cannot be expressed")
}

func (g *scGen) emitFor(fs *ast.ForStmt) error {
	groupID := g.nextGroupID()
	switch fs.Form {
	case "range":
		// A Repeat count is written into the workflow, so it has to be known
		// here. The fallback used to be 10 — a range whose bounds were anything
		// but literals silently became ten iterations, which is a wrong answer
		// wearing a successful compile.
		startLit, okStart := fs.Start.(*ast.Literal)
		endLit, okEnd := fs.End.(*ast.Literal)
		if !okStart || !okEnd {
			return fmt.Errorf("XQL_E402: a Shortcuts Repeat needs a literal count, and this range's bounds are computed")
		}
		startF, _ := startLit.Value.(float64)
		endF, _ := endLit.Value.(float64)
		count := int(endF - startF)
		g.addAction("is.workflow.actions.repeat.count", map[string]interface{}{
			"WFControlFlowMode":  0,
			"WFRepeatCount":      count,
			"GroupingIdentifier": groupID,
		})
		for _, s := range fs.Body {
			if err := g.emitStmt(s); err != nil {
				return err
			}
		}
		g.addAction("is.workflow.actions.repeat.count", map[string]interface{}{
			"WFControlFlowMode":  2,
			"GroupingIdentifier": groupID,
		})
	case "each":
		if fs.Iterable != nil {
			if err := g.emitExpr(fs.Iterable); err != nil {
				return err
			}
		}
		g.addAction("is.workflow.actions.repeat.each", map[string]interface{}{
			"WFControlFlowMode":  0,
			"GroupingIdentifier": groupID,
		})
		for _, s := range fs.Body {
			if err := g.emitStmt(s); err != nil {
				return err
			}
		}
		g.addAction("is.workflow.actions.repeat.each", map[string]interface{}{
			"WFControlFlowMode":  2,
			"GroupingIdentifier": groupID,
		})
	}
	return nil
}

func (g *scGen) emitMatch(me *ast.MatchExpr) error {
	if err := g.emitExpr(me.Value); err != nil {
		return err
	}
	g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
		"WFVariableName": "_match",
	})

	for _, arm := range me.Arms {
		if ident, ok := arm.Pattern.(*ast.Ident); ok && ident.Name == "_" {
			g.addComment("default")
			for _, s := range arm.Body {
				if err := g.emitStmt(s); err != nil {
					return err
				}
			}
		} else {
			groupID := g.nextGroupID()
			g.addAction("is.workflow.actions.getvariable", map[string]interface{}{
				"WFVariable": scVarRef("_match"),
			})
			params := map[string]interface{}{
				"WFControlFlowMode":  0,
				"GroupingIdentifier": groupID,
				"WFCondition":        0,
			}
			g.setConditionValue(params, arm.Pattern)
			g.addAction("is.workflow.actions.conditional", params)

			for _, s := range arm.Body {
				if err := g.emitStmt(s); err != nil {
					return err
				}
			}

			g.addAction("is.workflow.actions.conditional", map[string]interface{}{
				"WFControlFlowMode":  2,
				"GroupingIdentifier": groupID,
			})
		}
	}
	return nil
}

// --- expressions ---

func (g *scGen) emitExpr(n ast.Node) error {
	switch node := n.(type) {
	case *ast.Literal:
		return g.emitLiteral(node)
	case *ast.Ident:
		g.addAction("is.workflow.actions.getvariable", map[string]interface{}{
			"WFVariable": scVarRef(node.Name),
		})
		return nil
	case *ast.BinaryExpr:
		return g.emitBinary(node)
	case *ast.UnaryExpr:
		return g.emitUnary(node)
	case *ast.CallExpr:
		return g.emitCallExpr(node)
	case *ast.IfExpr:
		return g.emitExpr(node.Then)
	case *ast.MemberExpr:
		if ident, ok := node.Object.(*ast.Ident); ok {
			g.addAction("is.workflow.actions.getvariable", map[string]interface{}{
				"WFVariable": scVarRef(ident.Name),
			})
		}
		return nil
	case *ast.StructLit:
		g.addComment("struct " + node.TypeName + " literal")
		if len(node.Fields) > 0 {
			return g.emitExpr(node.Fields[0].Value)
		}
		return nil
	case *ast.ArrayLit:
		g.addComment("array literal")
		if len(node.Elements) > 0 {
			return g.emitExpr(node.Elements[0])
		}
		return nil
	case *ast.IndexExpr:
		return g.emitExpr(node.Target)
	case *ast.Lambda:
		g.addComment("lambda")
		return nil
	default:
		return nil
	}
}

func (g *scGen) emitLiteral(lit *ast.Literal) error {
	switch lit.ValueType {
	case "String":
		s, _ := lit.Value.(string)
		g.addAction("is.workflow.actions.text", map[string]interface{}{
			"WFTextActionText": s,
		})
	case "Int":
		f, _ := lit.Value.(float64)
		g.addAction("is.workflow.actions.number", map[string]interface{}{
			"WFNumberActionNumber": int64(f),
		})
	case "Float":
		f, _ := lit.Value.(float64)
		g.addAction("is.workflow.actions.number", map[string]interface{}{
			"WFNumberActionNumber": f,
		})
	case "Bool":
		b, _ := lit.Value.(bool)
		v := 0
		if b {
			v = 1
		}
		g.addAction("is.workflow.actions.number", map[string]interface{}{
			"WFNumberActionNumber": v,
		})
	default:
		g.addAction("is.workflow.actions.text", map[string]interface{}{
			"WFTextActionText": fmt.Sprintf("%v", lit.Value),
		})
	}
	return nil
}

func (g *scGen) emitBinary(be *ast.BinaryExpr) error {
	if be.Op == "+" && stringValued(g.types, be) {
		return g.emitStringConcat(be)
	}

	switch be.Op {
	case "==", "!=", "<", ">", "<=", ">=", "&&", "||":
		if err := g.emitExpr(be.Left); err != nil {
			return err
		}
		return nil
	}

	rightSimple := g.isSimple(be.Right)
	if !rightSimple {
		if err := g.emitExpr(be.Right); err != nil {
			return err
		}
		tmp := g.nextTmp()
		g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
			"WFVariableName": tmp,
		})
		if err := g.emitExpr(be.Left); err != nil {
			return err
		}
		g.addAction("is.workflow.actions.math", map[string]interface{}{
			"WFMathOperation": g.mathOp(be.Op),
			"WFMathOperand":   scVarRef(tmp),
		})
		return nil
	}

	if err := g.emitExpr(be.Left); err != nil {
		return err
	}
	operand := g.buildOperand(be.Right)
	g.addAction("is.workflow.actions.math", map[string]interface{}{
		"WFMathOperation": g.mathOp(be.Op),
		"WFMathOperand":   operand,
	})
	return nil
}

func (g *scGen) emitStringConcat(be *ast.BinaryExpr) error {
	if err := g.emitExpr(be.Left); err != nil {
		return err
	}
	leftTmp := g.nextTmp()
	g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
		"WFVariableName": leftTmp,
	})
	if err := g.emitExpr(be.Right); err != nil {
		return err
	}
	rightTmp := g.nextTmp()
	g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
		"WFVariableName": rightTmp,
	})
	g.addAction("is.workflow.actions.text", map[string]interface{}{
		"WFTextActionText": map[string]interface{}{
			"WFSerializationType": "WFTextTokenString",
			"Value": map[string]interface{}{
				"string": "￼￼",
				"attachmentsByRange": map[string]interface{}{
					"{0, 1}": map[string]interface{}{
						"Type":         "Variable",
						"VariableName": leftTmp,
					},
					"{1, 1}": map[string]interface{}{
						"Type":         "Variable",
						"VariableName": rightTmp,
					},
				},
			},
		},
	})
	return nil
}

func (g *scGen) emitUnary(ue *ast.UnaryExpr) error {
	if ue.Op == "-" {
		g.addAction("is.workflow.actions.number", map[string]interface{}{
			"WFNumberActionNumber": 0,
		})
		operand := g.buildOperand(ue.Operand)
		g.addAction("is.workflow.actions.math", map[string]interface{}{
			"WFMathOperation": "-",
			"WFMathOperand":   operand,
		})
		return nil
	}
	if ue.Op == "!" {
		return g.emitExpr(ue.Operand)
	}
	return g.emitExpr(ue.Operand)
}

func (g *scGen) emitCallExpr(ce *ast.CallExpr) error {
	switch ce.Callee {
	case "sprintf":
		if len(ce.Args) > 0 {
			return g.emitExpr(ce.Args[0])
		}
		return nil
	case "println", "printf":
		if len(ce.Args) > 0 {
			return g.emitExpr(ce.Args[0])
		}
		return nil
	default:
		fd, ok := g.funcs[ce.Callee]
		if !ok {
			g.addComment("call " + ce.Callee)
			return nil
		}
		if g.callDepth > 10 {
			g.addComment("call " + ce.Callee + " (recursion limit)")
			return nil
		}
		g.callDepth++
		defer func() { g.callDepth-- }()
		for i, arg := range ce.Args {
			if i < len(fd.Params) {
				if err := g.emitExpr(arg); err != nil {
					return err
				}
				g.addAction("is.workflow.actions.setvariable", map[string]interface{}{
					"WFVariableName": fd.Params[i].Name,
				})
			}
		}
		for _, stmt := range fd.Body {
			if err := g.emitStmt(stmt); err != nil {
				return err
			}
		}
		return nil
	}
}

// --- helpers ---

func (g *scGen) isSimple(n ast.Node) bool {
	switch n.(type) {
	case *ast.Literal, *ast.Ident:
		return true
	}
	return false
}

func (g *scGen) mathOp(op string) string {
	switch op {
	case "*":
		return "×"
	case "/":
		return "÷"
	case "%":
		return "Modulus"
	default:
		return op
	}
}

func (g *scGen) buildOperand(n ast.Node) interface{} {
	switch node := n.(type) {
	case *ast.Literal:
		switch node.ValueType {
		case "Int":
			f, _ := node.Value.(float64)
			return scTextToken(fmt.Sprintf("%d", int64(f)))
		case "Float":
			f, _ := node.Value.(float64)
			return scTextToken(fmt.Sprintf("%g", f))
		}
	case *ast.Ident:
		return scVarRef(node.Name)
	}
	return scTextToken("0")
}
